// K 线图「怎么用」里的说明文字（HTML）：每个工具、每个图层在这套方法里看什么。
const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

/**
 * 讲着色的那一段（放进下面 data-help="tone" 的那个 <p>）：颜色按什么规则算、怎么读，照图上现在这份颜色的来源写。
 * tone 是 tones.js 的 toneInfo：{ name, legend, warning }；日线、周线各一份，换了就重写。
 */
export function toneHelp(tone) {
  const source = tone.name ? `现在用的是「${esc(tone.name)}」：` : "";
  const legend = tone.legend.map((line) => `<br>${esc(line)}`).join("");
  const warning = tone.warning ? `<br><span class="help-warn">${esc(tone.warning)}</span>` : "";
  return `<b>着色</b>（默认不画，在「图层」里开）：K 线按信号上色，阳线空心、阴线实心。颜色是分析时算好的，日线、周线各算各的。${source}${legend}${warning}`;
}

